def get_levels() -> List[Dict]:
    return BBS_LEVELS


def get_level(level_id: str) -> Optional[Dict]:
    return next((level for level in BBS_LEVELS if level["id"] == level_id), None)


def get_modules_by_level(level_id: str) -> List[Dict]:
    return [module for module in BBS_MODULES if module["level"] == level_id]


def get_module(module_id: str) -> Optional[Dict]:
    return next((module for module in BBS_MODULES if module["id"] == module_id), None)


def format_level_overview(level_id: str) -> str:
    level = get_level(level_id)
    if not level:
        return "Раздел не найден."

    modules = get_modules_by_level(level_id)
    lines = [f"{level['title']}", level["subtitle"], "", "**Модули:**"]

    last_track = None
    for module in modules:
        track = module.get("track")
        if track and track != last_track:
            lines.extend(["", f"**Трек {track}:**"])
            last_track = track
        lines.append(f"• {module['code']} — {module['title']}")

    return "\n".join(lines)


def format_module(module_id: str) -> str:
    module = get_module(module_id)
    if not module:
        return "Модуль не найден."

    lines = [
        f"🧠 **{module['code']} — {module['title']}**",
        f"К уроку: {module['lesson']}",
    ]

    if module.get("track"):
        lines.append(f"Трек: {module['track']}")

    lines.extend(["", "**Нейрофизиологическая основа:**"])
    lines.extend(f"• {item}" for item in module["basis"])
    lines.extend(["", f"**Связь с практикой:** {module['practice']}"])
    lines.extend(["", f"**Вопрос в журнал:** {JOURNAL_PROMPT}"])

    return "\n".join(lines)
